const COUNT = ['no', 'one', 'two', 'three', 'four', 'five'];
/** "three memories": what a spawn carries, in words. */
export function memoryCount(n: number): string {
  return `${COUNT[n] ?? n} memor${n === 1 ? 'y' : 'ies'}`;
}

